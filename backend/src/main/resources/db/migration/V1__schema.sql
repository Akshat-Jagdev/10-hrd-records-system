-- HRD Records System schema. All data in this database is SYNTHETIC sample data.
--
-- Flyway V1: full DDL. Column types and lengths mirror the JPA entities under
-- com.hrd.records exactly (camelCase fields -> snake_case columns) so that
-- hibernate ddl-auto=validate passes against this schema.

CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    VARCHAR(50)  NOT NULL,
    password    VARCHAR(255) NOT NULL,
    full_name   VARCHAR(100) NOT NULL,
    role        VARCHAR(20)  NOT NULL,
    enabled     BOOLEAN      NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_users_username UNIQUE (username)
);

CREATE TABLE departments (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(10)  NOT NULL,
    name VARCHAR(100) NOT NULL,
    type VARCHAR(20)  NOT NULL,
    CONSTRAINT uk_departments_code UNIQUE (code)
);

CREATE TABLE employees (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_no        VARCHAR(20)  NOT NULL,
    full_name     VARCHAR(100) NOT NULL,
    grade         VARCHAR(10)  NOT NULL,
    designation   VARCHAR(100) NOT NULL,
    department_id BIGINT       NOT NULL,
    doj           DATE         NOT NULL,
    status        VARCHAR(20)  NOT NULL,
    basic_pay     NUMERIC(12,2) NOT NULL,
    CONSTRAINT uk_employees_emp_no UNIQUE (emp_no),
    CONSTRAINT fk_employees_department FOREIGN KEY (department_id) REFERENCES departments (id)
);

CREATE TABLE production_records (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id  BIGINT NOT NULL,
    year           INTEGER NOT NULL,
    month          INTEGER NOT NULL,
    planned_tonnes NUMERIC(12,2) NOT NULL,
    actual_tonnes  NUMERIC(12,2) NOT NULL,
    CONSTRAINT uk_production_period UNIQUE (department_id, year, month),
    CONSTRAINT fk_production_records_department FOREIGN KEY (department_id) REFERENCES departments (id)
);

CREATE TABLE incentive_schemes (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(100) NOT NULL,
    description    VARCHAR(500),
    threshold_pct  NUMERIC(5,2)  NOT NULL,
    ceiling_pct    NUMERIC(5,2)  NOT NULL,
    rate_per_point NUMERIC(10,2) NOT NULL,
    active         BOOLEAN       NOT NULL,
    effective_from DATE          NOT NULL,
    effective_to   DATE,
    CONSTRAINT uk_incentive_schemes_name UNIQUE (name)
);

CREATE TABLE scheme_grade_rates (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grade     VARCHAR(10)  NOT NULL,
    factor    NUMERIC(4,2) NOT NULL,
    scheme_id BIGINT       NOT NULL,
    CONSTRAINT uk_scheme_grade_rates_scheme_grade UNIQUE (scheme_id, grade),
    CONSTRAINT fk_scheme_grade_rates_scheme FOREIGN KEY (scheme_id) REFERENCES incentive_schemes (id)
);

CREATE TABLE incentive_earnings (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id     BIGINT NOT NULL,
    scheme_id       BIGINT NOT NULL,
    year            INTEGER NOT NULL,
    month           INTEGER NOT NULL,
    achievement_pct NUMERIC(7,2)  NOT NULL,
    amount          NUMERIC(12,2) NOT NULL,
    status          VARCHAR(20)   NOT NULL,
    decided_by      VARCHAR(50),
    decided_at      TIMESTAMPTZ,
    CONSTRAINT fk_incentive_earnings_employee FOREIGN KEY (employee_id) REFERENCES employees (id),
    CONSTRAINT fk_incentive_earnings_scheme FOREIGN KEY (scheme_id) REFERENCES incentive_schemes (id)
);

-- Append-only mutation trail. old_value/new_value hold DTO snapshots as JSON
-- (null on CREATE / DELETE respectively).
CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMPTZ  NOT NULL,
    username    VARCHAR(50)  NOT NULL,
    action      VARCHAR(10)  NOT NULL,
    entity      VARCHAR(50)  NOT NULL,
    entity_id   VARCHAR(64)  NOT NULL,
    old_value   JSONB,
    new_value   JSONB
);
